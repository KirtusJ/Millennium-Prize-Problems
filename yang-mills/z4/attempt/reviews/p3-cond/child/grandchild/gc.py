"""gc.py -- predicates fixed BEFORE first run.
G1: n in 1..10000, theta=1.0 rad, phi_n = (n*theta) mod 2pi, target 0.5.
    d_n = circular distance |phi_n-0.5| (min over wrap). Predicate: min_n d_n < 1e-3.
    Also Frobenius ||R(phi_n)-R(0.5)||_F = 2*sqrt(2)*sin(d/2) ~ sqrt(2)*d, so the
    stated tolerance 1e-3*sqrt(2) is the small-angle equivalent of d<1e-3 (slightly
    stricter in exact terms, differing at O(d^3)); report both, judge by d<1e-3.
G2: theta=pi/2. Group generated by R_theta (x1,x2-plane of R^4) and all 384 signed
    permutation matrices of R^4; BFS closure on integer matrices (entries rounded).
    Predicate: group size == 384. Also report whether rotation by 0.5 is in group
    (expected: no; its entries are non-integer cos .5, sin .5).
Tolerance sources: float64 mod 2pi of n*theta (error ~1e-12, far below 1e-3);
    rounding in R_{pi/2} (cos pi/2 ~ 6e-17) removed by rounding to int, checked
    to be within 1e-9 of integers. Deterministic; seed fixed (np seed 0, unused).
Outputs opened with mode "x". Rerun: python3 gc.py > out.txt is NOT used; see below.
"""
import sys, itertools
import numpy as np
np.random.seed(0)

def R2(a): return np.array([[np.cos(a), -np.sin(a)], [np.sin(a), np.cos(a)]])

# G1
n = np.arange(1, 10001)
phi = np.mod(n * 1.0, 2 * np.pi)
d = np.abs(phi - 0.5); d = np.minimum(d, 2 * np.pi - d)
i = int(np.argmin(d)); best = int(n[i]); dmin = float(d[i])
fro = float(np.linalg.norm(R2(phi[i]) - R2(0.5)))
g1 = dmin < 1e-3
print(f"G1 best n={best} phi_n={phi[i]:.12f} min_dist={dmin:.3e} fro={fro:.3e} "
     f"fro_tol={1e-3*np.sqrt(2):.3e} fro_exact_tol={2*np.sqrt(2)*np.sin(5e-4):.3e}")
print("G1", "MET" if g1 else "FAILED", "(min<1e-3)")

# G2
th = np.pi / 2
R = np.eye(4); R[:2, :2] = R2(th)
assert np.abs(R - np.round(R)).max() < 1e-9
Ri = np.round(R).astype(int)
gens = []
for p in itertools.permutations(range(4)):
    for s in itertools.product([1, -1], repeat=4):
        M = np.zeros((4, 4), int)
        for r, c in enumerate(p): M[r, c] = s[r]
        gens.append(M)
assert len(gens) == 384
gens.append(Ri)
key = lambda M: M.tobytes()
I = np.eye(4, dtype=int)
seen = {key(I): I}; fr = [I]
while fr:
    nf = []
    for A in fr:
        for G in gens:
            B = A @ G
            k = key(B)
            if k not in seen: seen[k] = B; nf.append(B)
    fr = nf
size = len(seen)
R05 = np.eye(4); R05[:2, :2] = R2(0.5)
in05 = any(np.abs(M - R05).max() < 1e-9 for M in seen.values())
print(f"G2 group size={size} rotation_0.5_in_group={in05}")
print("G2", "MET" if size == 384 else "FAILED", "(size==384)")
